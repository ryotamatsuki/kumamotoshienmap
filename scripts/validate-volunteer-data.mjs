import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {dirname,join} from "node:path";
import {fileURLToPath} from "node:url";
import {extractPageRecheckMeta} from "./current-page-metadata.mjs";

const root=join(dirname(fileURLToPath(import.meta.url)),"..");
const source=readFileSync(join(root,"volunteer-data.js"),"utf8");
const m=source.match(/^globalThis\.VOLUNTEER_DATA = Object\.freeze\(([\s\S]+)\);\s*$/u);
assert.ok(m);
const d=JSON.parse(m[1]);
const html=readFileSync(join(root,"ehime_kumamoto_support_geocoded_shelters_20260802.html"),"utf8");
const pm=extractPageRecheckMeta(html);
assert.equal(d.centers.length,11);
assert.equal(d.all_municipalities.length,45);
assert.equal(d.all_centers.length,45);
assert.equal(d.meta.reference_at,"2026-09-24T18:27:00+09:00");
assert.equal(d.meta.checked_at,pm.volunteerCheckedAt);
assert.match(String(d.meta.latest_audit||""),/^volunteer-source-recheck-20260924-1827\.json$/u);

const C=Object.fromEntries(d.centers.map(x=>[x.municipality,x]));
assert.ok(C["熊本市"].recruitment_status.includes("第7期"));
assert.equal(C["熊本市"].eligibility_currently_applicable,false);
assert.equal(C["熊本市"].activity_start_date,"2026-09-21");
assert.equal(C["熊本市"].activity_end_date,"2026-09-27");
assert.ok(C["宇土市"].recruitment_status.includes("第8期")&&C["宇土市"].recruitment_status.startsWith("募集中"));
assert.equal(C["宇土市"].outside_prefecture_allowed,true);
assert.equal(C["宇土市"].group_allowed,false);
assert.equal(C["宇土市"].activity_start_date,"2026-09-28");
assert.equal(C["宇土市"].activity_end_date,"2026-10-04");
assert.ok(C["宇城市"].recruitment_status.startsWith("募集中"));
assert.equal(C["宇城市"].eligibility_currently_applicable,true);
assert.equal(C["宇城市"].activity_end_date,"2026-10-12");
assert.ok(C["美里町"].recruitment_status.startsWith("募集中"));
assert.ok(C["八代市"].recruitment_status.startsWith("募集中")&&C["八代市"].recruitment_status.includes("第6弾"));
assert.equal(C["八代市"].group_allowed,true);
assert.ok(C["芦北町"].center_status.includes("閉所"));
assert.equal(C["芦北町"].eligibility_currently_applicable,false);
for(const n of ["御船町","嘉島町","益城町","甲佐町","氷川町"])assert.equal(C[n].eligibility_currently_applicable,false,`${n}を旧日程から現行募集扱いしています`);
const accepting=d.centers.filter(x=>String(x.recruitment_status||"").startsWith("募集中")&&x.eligibility_currently_applicable!==false);
assert.deepEqual(accepting.map(x=>x.municipality).sort(),["八代市","宇土市","宇城市","美里町"].sort());
for(const s of d.sources)assert.match(s.url,/^https?:\/\//u);
console.log(JSON.stringify({status:"PASS",reference_at:d.meta.reference_at,currentlyAccepting:accepting.map(x=>x.municipality),centers:d.centers.length,sources:d.sources.length}));
